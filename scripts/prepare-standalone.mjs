import {cp,mkdir} from 'node:fs/promises';
import {resolve,join,relative} from 'node:path';
const root=process.cwd(),target=resolve(root,'.next/standalone');
if(relative(root,target).startsWith('..'))throw Error('Standalone output escaped workspace.');
await mkdir(target,{recursive:true});
await cp(join(root,'public'),join(target,'public'),{recursive:true,filter:source=>{const p=relative(join(root,"public"),source).replaceAll("\\","/");return !p.startsWith("hot-seat/")||["hot-seat/runtime-v2","hot-seat/neural-v2","hot-seat/voice-worker-v2.mjs"].some(base=>p===base||p.startsWith(base+"/"))}});
await cp(join(root,'.next/static'),join(target,'.next/static'),{recursive:true});
await mkdir(join(target,'ops'),{recursive:true});
await cp(join(root,'deploy/ai-control.mjs'),join(target,'ops/ai-control.mjs'));
await cp(join(root,'scripts/backup-data.mjs'),join(target,'ops/backup-data.mjs'));
console.log('Standalone server includes public assets and versioned client files.');
